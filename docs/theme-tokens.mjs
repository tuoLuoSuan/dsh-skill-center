/**
 * Extract DSH's real design tokens out of the theme plugin's inlined CSS and
 * write them to `docs/theme.css`, so the headless design preview can render the
 * panel against the same palette the live app uses.
 *
 *   node docs/theme-tokens.mjs
 *
 * The theme plugin bundles two rule blocks that matter:
 *   body                        -> light
 *   body[data-ds-dark-theme]    -> dark
 * plus the `--dsw-static-*` palette they both reference.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { homedir } from 'node:os'

const here = dirname(fileURLToPath(import.meta.url))

// DSH keeps the theme plugin in more than one place depending on how it was
// installed, so try them in order instead of assuming.
const CANDIDATES = [
  process.env.SKILL_CENTER_THEME,
  join(homedir(), '.dsh', 'profiles', 'desktop', 'node_modules'),
  join(homedir(), '.dsh', 'profiles', 'node_modules'),
].filter(Boolean).map((base) =>
  base.endsWith('client.js')
    ? base
    : join(base, '@deepseek-ai', 'dsh-client-ui-theme', 'lib', 'client.js'),
)

const themeFile = CANDIDATES.find((candidate) => existsSync(candidate))
if (themeFile === undefined) {
  console.error('Could not find @deepseek-ai/dsh-client-ui-theme/lib/client.js.')
  console.error('Looked in:')
  for (const candidate of CANDIDATES) console.error(`  ${candidate}`)
  console.error('Set SKILL_CENTER_THEME to the file itself and try again.')
  process.exit(2)
}
console.log(`reading ${themeFile}`)

const source = readFileSync(themeFile, 'utf8')

/** Find the CSS rule whose body contains `anchor`, returning its full text. */
function ruleAround(anchor) {
  const at = source.indexOf(anchor)
  if (at === -1) throw new Error(`anchor not found: ${anchor}`)
  const open = source.lastIndexOf('{', at)
  const close = source.indexOf('}', at)
  if (open === -1 || close === -1) throw new Error(`unbalanced rule for ${anchor}`)
  const selectorStart = Math.max(
    source.lastIndexOf('}', open),
    source.lastIndexOf(';', open),
    source.lastIndexOf('"', open),
    source.lastIndexOf("'", open),
  )
  return source.slice(selectorStart + 1, close + 1).trim()
}

/**
 * Collect every top-level `selector{...}` rule whose selector is one of the
 * theme roots, preserving source order so the cascade behaves like the app.
 * The theme plugin splits its tokens across several rules per selector.
 */
function rulesFor(selectors) {
  const found = []
  for (const selector of selectors) {
    const needle = `${selector}{`
    let at = source.indexOf(needle)
    while (at !== -1) {
      const close = source.indexOf('}', at)
      if (close === -1) break
      found.push({ at, text: source.slice(at, close + 1) })
      at = source.indexOf(needle, close)
    }
  }
  return found.sort((a, b) => a.at - b.at).map((rule) => rule.text)
}

// The theme plugin declares tokens on `body` (light) and on
// `body[data-ds-dark-theme]` (dark), each split across several rules.
const lightRules = rulesFor(['body'])
const darkRules = rulesFor(['body[data-ds-dark-theme]'])

const count = (rules) =>
  rules.reduce((total, rule) => total + (rule.match(/--dsw-[a-z0-9-]+(?=\s*:)/g) ?? []).length, 0)

const css = [
  '/* Generated by docs/theme-tokens.mjs — DSH design tokens, light + dark. */',
  ...lightRules,
  '',
  ...darkRules,
  '',
].join('\n')

writeFileSync(join(here, 'theme.css'), css, 'utf8')

console.log(`light   : ${lightRules.length} rules, ${count(lightRules)} declarations`)
console.log(`dark    : ${darkRules.length} rules, ${count(darkRules)} declarations`)
console.log(`-> docs/theme.css (${css.length} chars)`)

// A couple of sanity anchors the preview depends on.
for (const [theme, rules, probe] of [
  ['light', lightRules, '--dsw-alias-label-primary:'],
  ['dark', darkRules, '--dsw-alias-label-primary:'],
]) {
  const joined = rules.join('')
  const at = joined.lastIndexOf(probe)
  console.log(`  ${theme} ${probe} -> ${at === -1 ? 'MISSING' : joined.slice(at + probe.length).split(/[;}]/)[0]}`)
}
